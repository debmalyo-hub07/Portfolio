/**
 * Detects the newest résumé in public/resume and writes src/content/resume.generated.ts.
 * Runs automatically before `dev` and `build`. Drop a new .pdf/.docx/.doc in public/resume — no code changes.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";

const DIR = join(process.cwd(), "public", "resume");
const OUT = join(process.cwd(), "src", "content", "resume.generated.ts");
const EXT = [".pdf", ".docx", ".doc"] as const;
type Ext = (typeof EXT)[number];

interface FileInfo {
  href: string;
  ext: Ext;
  sizeKB: number;
  updatedISO: string;
}

/**
 * Prefer the date embedded in the document (survives git clone on Vercel, where mtime = checkout time).
 * PDF: /ModDate or /CreationDate. DOCX: docProps/core.xml is zipped, so fall back to mtime.
 */
function embeddedDate(path: string, ext: Ext): Date | null {
  if (ext !== ".pdf") return null;
  const text = readFileSync(path).toString("latin1");
  const m = /\/(?:ModDate|CreationDate)\s*\(D:(\d{4})(\d{2})(\d{2})(\d{2})?(\d{2})?(\d{2})?/.exec(text);
  if (!m) return null;
  const [, y, mo, d, h = "00", mi = "00", se = "00"] = m;
  const date = new Date(`${y}-${mo}-${d}T${h}:${mi}:${se}Z`);
  return Number.isNaN(date.getTime()) ? null : date;
}

function scan(): FileInfo[] {
  let names: string[] = [];
  try {
    names = readdirSync(DIR);
  } catch {
    return [];
  }
  return names
    .filter((n) => !n.startsWith(".") && (EXT as readonly string[]).includes(extname(n).toLowerCase()))
    .map((n) => {
      const path = join(DIR, n);
      const ext = extname(n).toLowerCase() as Ext;
      const st = statSync(path);
      const updated = embeddedDate(path, ext) ?? st.mtime;
      return {
        href: `/resume/${encodeURIComponent(n)}`,
        ext,
        sizeKB: Math.max(1, Math.round(st.size / 1024)),
        updatedISO: updated.toISOString(),
      };
    })
    .sort((a, b) => b.updatedISO.localeCompare(a.updatedISO));
}

const files = scan();
if (files.length === 0) {
  console.error(
    "\n[sync-resume] No résumé found in public/resume/. Add a .pdf, .docx or .doc file and re-run.\n",
  );
  process.exit(1);
}

const pick = (exts: Ext[]) => files.find((f) => exts.includes(f.ext));
const primary = pick([".pdf"]) ?? files[0];
const alt = primary.ext === ".pdf" ? pick([".docx", ".doc"]) : undefined;
const data = { primary, alt: alt ?? null };
writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/sync-resume.ts — do not edit.\nimport type { ResumeData } from "@/lib/resume";\n\nexport const resume: ResumeData = ${JSON.stringify(data, null, 2)};\n`,
);
console.log(`[sync-resume] primary: ${primary.href}${alt ? ` · alt: ${alt.href}` : ""}`);
